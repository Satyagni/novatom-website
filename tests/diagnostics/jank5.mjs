import { chromium } from 'playwright';
import fs from 'fs';
const b = await chromium.launch({ headless: true, args: ['--use-angle=d3d11', '--ignore-gpu-blocklist'] });
const page = await (await b.newContext({ viewport: { width: 1440, height: 800 } })).newPage();
await page.goto('http://127.0.0.1:4173/', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(7000);
console.log(await page.evaluate(() => ['.nav', '.rail', '.hero-copy'].map((s) => { const e = document.querySelector(s); const c = getComputedStyle(e); return s + ' op=' + c.opacity + ' inline=' + e.style.opacity + ' tf=' + c.transform; }).join(' | ')));
await b.startTracing(page, { path: 'tests/shots/trace2.json', categories: ['devtools.timeline', 'gpu', 'cc', 'toplevel'] });
await page.mouse.click(700, 300);
await page.waitForTimeout(6000);
await b.stopTracing();
const t = JSON.parse(fs.readFileSync('tests/shots/trace2.json', 'utf8'));
const ev = t.traceEvents || t;
const g = ev.filter((e) => e.name === 'GPUTask' && e.dur > 150000)[0];
console.log('stall dur', g && g.dur / 1000);
const rp = g.args.data.renderer_pid;
const paints = ev.filter((e) => e.pid === rp && e.name === 'Paint' && e.args?.data?.nodeName && e.args.data.nodeName !== '#document');
paints.slice(0, 12).forEach((e) => console.log(Math.round((e.ts - g.ts) / 1000), e.args.data.nodeName, JSON.stringify(e.args.data.clip)));
await b.close();
